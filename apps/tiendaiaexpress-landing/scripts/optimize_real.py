"""Optimise the real material used by the premium landing.

Reads  scripts/.stores/real/ (scripts/snapshot-real-stores.mjs): original product photos, phone
       captures and data.json of the AUTHORIZED stores;
       ../../docs/capturas-fabrica-creativos/: pieces generated by the platform's Estudio Creativo
       with the demonstration store (docs/FABRICA_CREATIVOS_FASE3.md);
       brand-originals/: owner artwork (cart isotype with transparency, assistant mascot).
Writes src/assets/real/, src/assets/studio/, src/assets/brand/ and src/content/realStores.json.
Photos are only resized and re-encoded: never recoloured, retouched or cropped off-centre.
Usage: python scripts/optimize_real.py
"""
import json
import re
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / 'scripts' / '.stores' / 'real'
FAB = ROOT.parent.parent / 'docs' / 'capturas-fabrica-creativos'
ORIG = ROOT / 'brand-originals'
REAL = ROOT / 'src' / 'assets' / 'real'
STUDIO = ROOT / 'src' / 'assets' / 'studio'
BRAND = ROOT / 'src' / 'assets' / 'brand'
for folder in (REAL, STUDIO, BRAND):
    folder.mkdir(parents=True, exist_ok=True)


def save(image, dest, width, quality=78):
    if image.width > width:
        image = image.resize((width, round(image.height * width / image.width)), Image.LANCZOS)
    image.save(dest, 'WEBP', quality=quality, method=6)
    print(dest.relative_to(ROOT), image.size, dest.stat().st_size // 1024, 'KB')
    return image.size


slug = lambda text: re.sub(r'[^a-z0-9]+', '-', text.lower()).strip('-')
data = json.loads((RAW / 'data.json').read_text(encoding='utf8'))
for store, info in data['stores'].items():
    for product in info['products']:
        image = Image.open(RAW / f"{store}--{product['sku']}.img").convert('RGB')
        name = f"{store}--{slug(product['sku'])}.webp"
        product['image'] = name
        product['width'], product['height'] = save(image, REAL / name, 640)
    phone = Image.open(RAW / f'{store}--mobile.png').convert('RGB')
    save(phone, REAL / f'{store}--movil.webp', 720, 74)
    save(phone, REAL / f'{store}--movil-480.webp', 480, 72)
(ROOT / 'src' / 'content' / 'realStores.json').write_text(json.dumps(data, ensure_ascii=False, indent=2) + '\n', encoding='utf8')

PIECES = {
    'oferta-vertical': ('imagen-oferta_aprobada-vertical.jpg', 720),
    'carrusel-1': ('carrusel-coleccion-cuadrado-1.jpg', 600),
    'carrusel-2': ('carrusel-coleccion-cuadrado-2.jpg', 600),
    'historia-catalogo': ('imagen-invitacion_catalogo-historia.png', 540),
    'ultimas-unidades': ('imagen-ultimas_unidades-whatsapp.png', 800),
}
for name, (file, width) in PIECES.items():
    save(Image.open(FAB / file).convert('RGB'), STUDIO / f'{name}.webp', width, 80)
# Three frames of a generated short video (conventional mode): one file per frame.
strip = Image.open(FAB / 'video-producto_nuevo-historia-cuadros.jpg').convert('RGB')
frame = strip.width // 3
for i in range(3):
    save(strip.crop((i * frame, 0, (i + 1) * frame, strip.height)), STUDIO / f'video-cuadro-{i + 1}.webp', 360, 80)

iso = Image.open(ORIG / 'isotipo-carrito-transparente.png').convert('RGBA')
iso = iso.crop(iso.getbbox())
for width in (96, 192):
    save(iso, BRAND / f'isotipo-carrito-{width}.webp', width, 90)
# Assistant mascot: head and shoulders only (square crop, own dark-green background).
mascot = Image.open(ORIG / 'mascota-asistente.webp').convert('RGB').crop((285, 0, 965, 680))
for width in (160, 480):
    save(mascot, BRAND / f'asistente-{width}.webp', width, 82)
