// Generates src/components/ui/brandIcons.ts from simple-icons (CC0-1.0). Run: node scripts/brand-icons.mjs
import { writeFileSync } from 'node:fs'
import { siWhatsapp, siTelegram, siInstagram, siFacebook, siTiktok } from 'simple-icons'

const icons = { whatsapp: siWhatsapp, telegram: siTelegram, instagram: siInstagram, facebook: siFacebook, tiktok: siTiktok }
const body = Object.entries(icons).map(([k, v]) => `  ${k}: '${v.path}',`).join('\n')
writeFileSync(new URL('../src/components/ui/brandIcons.ts', import.meta.url),
  `// Generated by scripts/brand-icons.mjs from simple-icons (CC0-1.0). 24×24 viewBox.\nexport const brandIcons = {\n${body}\n} as const\n\nexport type BrandIcon = keyof typeof brandIcons\n`)
console.log('ok')
